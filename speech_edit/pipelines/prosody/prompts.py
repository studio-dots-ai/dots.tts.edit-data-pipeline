def _reverse_example_precise(tagged_text: str) -> str:
    num_rate = tagged_text.count("<rate")
    parts: List[str] = []
    for value in re.findall(r"<pitch,\s*semitones=(-?\d+)>", tagged_text):
        semitones = int(value)
        direction = "lower" if semitones > 0 else "raise"
        parts.append(
            f"{direction} the pitch of the marked span by {abs(semitones)} semitones"
        )
    if num_rate:
        placeholders = ", ".join(["[[RATE_VALUE_PH]]x"] * num_rate)
        parts.append(f"change the marked rate span back to {placeholders}")
    text = " and ".join(parts)
    return text[:1].upper() + text[1:]


def _tagged_text_example(response: Dict[str, str], *, forward_nl_mode: str) -> Dict[str, Any]:
    tagged_text = response["tagged_text"]
    payload: Dict[str, Any] = {
        "normed_text": response["normed_text"],
        "tagged_text": tagged_text,
    }
    if forward_nl_mode == "llm":
        payload["forward_nl"] = {
            "precise": response["forward_precise"],
            "vague": response["forward_vague"],
        }
    return payload


def _wave_examples(edit_kind: str, span_level: str, normalized_language: str) -> List[Dict[str, str]]:
    if span_level == "sentence":
        examples = _ZH_SENTENCE_EXAMPLES if normalized_language == "zh" else _SENTENCE_EXAMPLES
    else:
        examples = _ZH_LOCAL_EXAMPLES if normalized_language == "zh" else _LOCAL_EXAMPLES
    if edit_kind not in examples:
        raise ValueError(
            f"Unsupported edit_kind/span_level combination: {edit_kind}/{span_level}"
        )
    return examples[edit_kind]


def _edit_kind_instruction(
    edit_kind: str,
    span_level: str,
    max_regions: int,
    target_num_regions: Optional[int] = None,
) -> str:
    if span_level == "sentence":
        if edit_kind == "pitch":
            return "Wrap all of normed_text in one pitch tag. No rate tags."
        if edit_kind == "rate":
            return "Wrap all of normed_text in one rate tag. No pitch tags."
        raise ValueError("sentence span does not support mixed edits")
    if edit_kind == "pitch":
        if target_num_regions is not None:
            return (
                f"Select exactly {target_num_regions} non-overlapping spans. "
                "Use pitch tags only; mix higher and lower values when natural."
            )
        return (
            f"Select 1-{max_regions} non-overlapping spans. Use pitch tags only; mix higher "
            "and lower values when natural."
        )
    if edit_kind == "rate":
        if target_num_regions is not None:
            return (
                f"Select exactly {target_num_regions} non-overlapping spans. "
                "Use rate tags only; mix faster and slower values when natural."
            )
        return (
            f"Select 1-{max_regions} non-overlapping spans. Use rate tags only; mix faster "
            "and slower values when natural."
        )
    if edit_kind == "mixed":
        if max_regions < 2:
            raise ValueError("mixed edits require max_regions >= 2")
        if target_num_regions is not None:
            return (
                f"Select exactly {target_num_regions} non-overlapping spans. "
                "Use at least one pitch tag and one rate tag on different spans."
            )
        return (
            f"Select 2-{max_regions} non-overlapping spans. Use at least one pitch tag and "
            "one rate tag on different spans."
        )
    raise ValueError(f"Unknown edit_kind: {edit_kind}")


def _response_skeleton(
    wave_configs: List[Dict[str, Any]],
    *,
    forward_nl_mode: str,
) -> Dict[str, Any]:
    waves: Dict[str, Any] = {}
    for config in wave_configs:
        wave_id = config["wave_id"]
        waves[wave_id] = {"tagged_text": "<normed_text with this wave's requested tags>"}
        if forward_nl_mode == "llm":
            waves[wave_id]["forward_nl"] = {
                "precise": "<exact edit values>",
                "vague": "<direction only, no numbers>",
            }
    return {"normed_text": "<preprocessed spoken-form text>", "waves": waves}


def build_prompt(
    transcript: str,
    *,
    wave_configs: List[Dict[str, Any]],
    pitch_values: List[int],
    rate_values: List[float],
    language: Optional[str] = None,
    forward_nl_mode: str = "template",
) -> str:
    """Build the complete multi-wave LLM prompt."""
    if forward_nl_mode not in {"template", "llm"}:
        raise ValueError("forward_nl_mode must be 'template' or 'llm'")
    if not wave_configs:
        raise ValueError("wave_configs must not be empty")
    for config in wave_configs:
        edit_kind = config.get("edit_kind")
        span_level = config.get("span_level")
        if edit_kind not in {"pitch", "rate", "mixed"}:
            raise ValueError(
                f"Unknown edit_kind: {edit_kind}. Valid: ['pitch', 'rate', 'mixed']"
            )
        if span_level is not None and span_level not in _SPAN_LEVEL_INSTRUCTIONS:
            raise ValueError(
                f"Unknown span_level: {span_level}. "
                f"Valid: {list(_SPAN_LEVEL_INSTRUCTIONS.keys())}"
            )
        if edit_kind == "mixed" and span_level == "sentence":
            raise ValueError("sentence span does not support mixed edits")

    normalized_language = (language or "en").lower()
    normalization_desc = (
        ZH_TEXT_NORMALIZATION_DESC
        if normalized_language == "zh"
        else TEXT_NORMALIZATION_DESC
    )
    few_shot_parts = ["\n## Examples\n"]
    example_keys = []
    for config in wave_configs:
        example_key = (config["edit_kind"], config["span_level"])
        if example_key not in example_keys:
            example_keys.append(example_key)
    for edit_kind, span_level in example_keys:
        for example in _wave_examples(edit_kind, span_level, normalized_language):
            few_shot_parts.append(f'Transcript: "{example["transcript"]}"')
            few_shot_parts.append(
                "Tagged-text example: "
                f"{json.dumps(_tagged_text_example(example['response'], forward_nl_mode=forward_nl_mode), ensure_ascii=False, separators=(',', ':'))}"
            )
            few_shot_parts.append("")
    few_shot = "\n".join(few_shot_parts)

    wave_lines = []
    for config in wave_configs:
        span_level = config.get("span_level")
        span_text = (
            _SPAN_LEVEL_INSTRUCTIONS[span_level]
            if span_level is not None
            else "Use the requested span granularity."
        )
        wave_lines.append(
            "\n".join(
                [
                    f'Wave "{config["wave_id"]}":',
                    f"Edit kind: {config['edit_kind']}.",
                    _edit_kind_instruction(
                        config["edit_kind"],
                        span_level,
                        int(config.get("max_regions", 3)),
                        (
                            int(config["target_num_regions"])
                            if config.get("target_num_regions") is not None
                            else None
                        ),
                    ),
                    span_text,
                    f'Max tagged edit spans: {int(config.get("max_regions", 3))}.',
                    (
                        f'Exact tagged edit spans: {int(config["target_num_regions"])}.'
                        if config.get("target_num_regions") is not None
                        else ""
                    ),
                ]
            )
        )
    wave_plan = "\n\n".join(wave_lines)
    required_wave_ids = [config["wave_id"] for config in wave_configs]
    skeleton = json.dumps(
        _response_skeleton(wave_configs, forward_nl_mode=forward_nl_mode),
        ensure_ascii=False,
        indent=2,
    )
    instruction_block = (
        f"## Instructions\n{FORWARD_INSTRUCTION_STYLE_DESC}\n"
        if forward_nl_mode == "llm"
        else "## Instructions\nDo not generate natural-language instructions in this response.\n"
    )
    output_format = (
        OUTPUT_FORMAT_WITH_FORWARD_NL
        if forward_nl_mode == "llm"
        else OUTPUT_FORMAT_TAGGED_ONLY
    )

    return f"""\
You are a speech editing instruction generator. Your job is to produce
pitch and/or speech-rate editing instructions for a text-to-speech dataset.

## Step 0: Text preprocessing
{normalization_desc}

## Tag format
{TAG_FORMAT_DESC}

## Wave plan
Generate all requested waves in one response. Each wave is an independent
generated target for the same original utterance. The `waves` object MUST
contain every required wave id exactly once: {json.dumps(required_wave_ids)}.

{wave_plan}

## Allowed parameter values
Use ONLY values from these lists. Do not invent, interpolate, round, or adjust
them. You may choose positive/negative pitch values for raising/lowering pitch,
and rate values above/below 1.0 for speeding up/slowing down speech.

- pitch_values: {json.dumps(pitch_values)}
- rate_values: {json.dumps(rate_values)}

Each wave must respect its own max tagged edit spans from the wave plan.

{instruction_block}
{few_shot}
## Output format
{output_format}

Required complete output skeleton:
{skeleton}

Now generate an edit instruction for the following transcript:

"{transcript}"
"""


def build_reverse_instruction_prompt(
    *,
    plain_text: str,
    waves: List[Dict[str, str]],
    language: Optional[str] = None,
) -> str:
    """Build a reverse-only NL prompt for already validated tagged waves."""
    normalized_language = (language or "en").lower()
    language_rule = (
        "Write Mandarin Chinese instructions."
        if normalized_language == "zh"
        else "Write English instructions."
    )
    payload = {
        "reverse_instructions": {
            str(wave["wave_id"]): {
                "nl": {
                    "precise": "<reverse edit; use [[RATE_VALUE_PH]] for each reverse rate value>",
                    "vague": "<direction only, no numbers>",
                }
            }
            for wave in waves
        }
    }
    return f"""\
You are a speech editing instruction generator. Generate only reverse
natural-language instructions for already validated pitch/rate tagged waves.

{language_rule}

Rules:
- Do not change or invent structural tags.
- Python already derived each reverse structural instruction; use it only as
  the semantic source of truth.
- `nl.precise` must describe exact reverse pitch/rate values.
- For every reverse rate edit, use the placeholder `{RATE_VALUE_PLACEHOLDER}`
  where the exact reciprocal value belongs. Python fills it later.
- `nl.vague` must contain no numbers, parameter values, or placeholders.

Plain text:
{json.dumps(plain_text, ensure_ascii=False)}

Waves:
{json.dumps(waves, ensure_ascii=False, indent=2)}

Respond with this JSON shape:
{json.dumps(payload, ensure_ascii=False, indent=2)}
"""
