def _decode_insert_audio(encoded: EncodedAudio, target_sample_rate: int) -> np.ndarray:
    audio_bytes = base64.b64decode(encoded.data)
    audio_buf = io.BytesIO(audio_bytes)
    insert_audio, insert_sr = sf.read(audio_buf, dtype="float32")
    if insert_audio.ndim > 1:
        insert_audio = insert_audio.mean(axis=1)
    insert_audio = insert_audio.astype(np.float32)
    if insert_sr != target_sample_rate:
        insert_audio = _resample(insert_audio, insert_sr, target_sample_rate)
    return insert_audio.astype(np.float32)


@app.get("/")
async def root():
    return {
        "service": "Boundary Pause Smoother",
        "version": "2.0.0",
        "docs": "/docs",
    }


@app.get("/health")
async def health():
    return {"status": "healthy", "version": "2.0.0"}


@app.post("/smooth")
async def smooth(request: SmoothRequest):
    """
    Smooth audio at specified boundary points.

    For each smoothing point:
    1. Resolves the native pause interval (explicit interval or aligner + VAD)
    2. Clamps or expands that pause to the requested duration bounds
    3. Regenerates the continuous mask region around the adjusted pause via F5-TTS

    Returns smoothed audio as WAV bytes or numpy tensor.
    """
    try:
        _t0 = time.time()

        # Decode input audio
        audio_bytes = base64.b64decode(request.audio.data)
        audio_buf = io.BytesIO(audio_bytes)
        audio, sample_rate = sf.read(audio_buf, dtype="float32")

        if audio.ndim > 1:
            audio = audio.mean(axis=1)  # Mono

        # Convert request points to SmoothingPoint objects
        points = []
        for idx, p in enumerate(request.points):
            audio_insert = None
            min_pause_sec = p.min_pause_sec
            max_pause_sec = p.max_pause_sec
            if p.audio_insert is not None:
                audio_insert = _decode_insert_audio(p.audio_insert, sample_rate)
                if len(audio_insert) == 0:
                    raise ValueError(f"points[{idx}].audio_insert must not be empty")
                forced_pause_sec = len(audio_insert) / sample_rate
                min_pause_sec = forced_pause_sec
                max_pause_sec = forced_pause_sec

            points.append(
                SmoothingPoint(
                    mode=p.mode,
                    position_sec=p.position_sec,
                    pause_interval_sec=p.pause_interval_sec,
                    max_pause_sec=max_pause_sec,
                    min_pause_sec=min_pause_sec,
                    regen_margin_sec=p.regen_margin_sec,
                    audio_insert=audio_insert,
                    audio_insert_intrusion_ratio=p.audio_insert_intrusion_ratio,
                )
            )

        # Run smoothing
        result = smooth_audio(
            audio=audio,
            sample_rate=sample_rate,
            text=request.text,
            points=points,
            f5tts_url=SERVICE_CONFIG["f5tts_url"],
            aligner_url=SERVICE_CONFIG["aligner_url"],
            aligner_backend=request.aligner_backend,
            language=request.language,
            vad_url=SERVICE_CONFIG["vad_url"],
            f5_steps=request.f5_steps,
            f5_cfg_strength=request.f5_cfg_strength,
            f5_sway_sampling_coef=request.f5_sway_sampling_coef,
            f5_seed=request.f5_seed,
            debug=request.debug,
            debug_dir=request.debug_dir,
        )

        _elapsed = time.time() - _t0

        # Format output
        if request.output_format == "wav":
            buf = io.BytesIO()
            sf.write(buf, result.audio, result.sample_rate, format="WAV")
            buf.seek(0)
            wav_bytes = buf.read()

            headers = {
                "Content-Disposition": "attachment; filename=smoothed.wav",
                "X-Sample-Rate": str(result.sample_rate),
                "X-Points-Processed": str(result.points_processed),
                "X-Duration-Sec": f"{len(result.audio) / result.sample_rate:.4f}",
                "X-Response-Time": f"{_elapsed:.3f}",
            }
            if request.debug and result.debug_dir:
                headers["X-Debug-Dir"] = result.debug_dir
            if request.trace_id:
                headers["X-Trace-Id"] = request.trace_id

            return Response(
                content=wav_bytes,
                media_type="audio/wav",
                headers=headers,
            )
        else:
            # numpy format
            tensor_data = {
                "data": base64.b64encode(
                    result.audio.astype(np.float32).tobytes()
                ).decode("utf-8"),
                "shape": list(result.audio.shape),
                "dtype": "float32",
            }
            return SmoothResponse(
                status="success",
                tensor=EncodedTensor(**tensor_data),
                sample_rate=result.sample_rate,
                points_processed=result.points_processed,
                details=result.details,
                duration_sec=len(result.audio) / result.sample_rate,
                response_time=round(_elapsed, 3),
                trace_id=request.trace_id,
            )

    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        logger.error(f"Smoothing failed: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Smoothing failed: {e}")


